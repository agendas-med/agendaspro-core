CREATE TABLE IF NOT EXISTS mp_destinations (
  company_id INT NOT NULL PRIMARY KEY,
  holder_name VARCHAR(150) NOT NULL,
  holder_document VARCHAR(14) NOT NULL,
  bank_name VARCHAR(100) NULL,
  pix_key_type VARCHAR(10) NOT NULL,
  pix_key VARCHAR(255) NOT NULL,
  updated_by INT NOT NULL,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_mp_destination_company FOREIGN KEY (company_id) REFERENCES companies(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS mp_charges (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  company_id INT NOT NULL,
  sale_id INT NOT NULL,
  customer_id INT NOT NULL,
  environment VARCHAR(10) NOT NULL,
  api_version VARCHAR(10) NOT NULL DEFAULT 'payments',
  external_reference VARCHAR(50) NOT NULL UNIQUE,
  idempotency_key VARCHAR(100) NOT NULL UNIQUE,
  request_body MEDIUMTEXT NOT NULL,
  provider_payment_id VARCHAR(100) NULL UNIQUE,
  amount_cents BIGINT NOT NULL,
  commission_bps INT NOT NULL,
  pix_payload TEXT NULL,
  pix_encoded_image MEDIUMTEXT NULL,
  pix_expiration_date VARCHAR(40) NULL,
  payment_url TEXT NULL,
  status VARCHAR(30) NOT NULL DEFAULT 'creating',
  last_error VARCHAR(255) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_mp_charge_company FOREIGN KEY (company_id) REFERENCES companies(id),
  CONSTRAINT fk_mp_charge_sale FOREIGN KEY (sale_id) REFERENCES sales(id),
  KEY idx_mp_charge_company (company_id, id),
  KEY idx_mp_charge_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS mp_payouts (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  charge_id INT NOT NULL UNIQUE,
  company_id INT NOT NULL,
  environment VARCHAR(10) NOT NULL,
  external_reference VARCHAR(50) NOT NULL UNIQUE,
  idempotency_key VARCHAR(100) NOT NULL UNIQUE,
  gross_cents BIGINT NOT NULL,
  provider_fee_cents BIGINT NOT NULL,
  commission_cents BIGINT NOT NULL,
  amount_cents BIGINT NOT NULL,
  destination_name VARCHAR(150) NOT NULL,
  destination_document VARCHAR(14) NOT NULL,
  pix_key_type VARCHAR(10) NOT NULL,
  pix_key VARCHAR(255) NOT NULL,
  request_body MEDIUMTEXT NOT NULL,
  provider_payout_id VARCHAR(100) NULL UNIQUE,
  provider_transaction_id VARCHAR(100) NULL UNIQUE,
  status VARCHAR(30) NOT NULL DEFAULT 'ready',
  status_detail VARCHAR(100) NULL,
  last_error VARCHAR(255) NULL,
  paid_at DATETIME NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_mp_payout_charge FOREIGN KEY (charge_id) REFERENCES mp_charges(id),
  KEY idx_mp_payout_company (company_id, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
